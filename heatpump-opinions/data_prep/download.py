"""Download the raw input datasets listed in `sources.py`.

Downloads are idempotent: an existing file of the right size is left alone, so
re-running is cheap. Every run rewrites `data/raw/MANIFEST.md` with the URL,
licence, retrieval date, size and SHA256 of each file -- these are pinned
snapshots of datasets that move (and, in Nesta's case, are being retired), so
the provenance record is the only way to reproduce a run later.

Usage:
    python -m data_prep.download            # fetch anything missing
    python -m data_prep.download --force    # re-fetch everything
"""
from __future__ import annotations

import argparse
import hashlib
import sys
import urllib.request
from datetime import date
from pathlib import Path

from .sources import SOURCES, Source

RAW_DIR = Path(__file__).resolve().parent.parent / "data" / "raw"
USER_AGENT = "heatpump-opinions research data collection (academic use)"


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _remote_size(url: str) -> int | None:
    req = urllib.request.Request(url, method="HEAD", headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            length = resp.headers.get("Content-Length")
            return int(length) if length else None
    except Exception:
        return None


def fetch(source: Source, force: bool = False) -> Path:
    """Download one source. Returns the path to the local file."""
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    dest = RAW_DIR / source.filename

    if dest.exists() and not force:
        expected = _remote_size(source.url)
        if expected is None or dest.stat().st_size == expected:
            print(f"  skip     {source.filename} (already present)")
            return dest
        print(f"  refetch  {source.filename} (size differs from remote)")

    # Download to a temporary name first so an interrupted run never leaves a
    # truncated file that a later run would treat as complete.
    tmp = dest.with_suffix(dest.suffix + ".partial")
    req = urllib.request.Request(source.url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=300) as resp, open(tmp, "wb") as out:
        while chunk := resp.read(1 << 20):
            out.write(chunk)
    tmp.replace(dest)

    print(f"  got      {source.filename} ({dest.stat().st_size / 1e6:.1f} MB)")
    return dest


def write_manifest(paths: dict[str, Path]) -> Path:
    """Record exactly what was downloaded, when, and under what licence."""
    lines = [
        "# Raw data manifest",
        "",
        "Generated by `python -m data_prep.download`. Do not edit by hand.",
        "",
        "These files are **not** committed -- they are large and some carry",
        "licences that restrict redistribution. Re-run the downloader to recreate",
        "them. The hashes below identify the exact snapshot a result was built on.",
        "",
    ]
    for source in SOURCES:
        path = paths.get(source.key)
        lines += [f"## {source.key}", ""]
        if path is None or not path.exists():
            lines += ["**NOT DOWNLOADED**", "", f"- URL: {source.url}", ""]
            continue
        lines += [
            f"- File: `{source.filename}`",
            f"- Description: {source.description}",
            f"- URL: {source.url}",
            f"- Source page: {source.source_page}",
            f"- Licence: {source.licence}",
            f"- LSOA vintage: {source.lsoa_vintage}",
            f"- Retrieved: {date.today().isoformat()}",
            f"- Size: {path.stat().st_size:,} bytes",
            f"- SHA256: `{_sha256(path)}`",
            "",
        ]
    manifest = RAW_DIR / "MANIFEST.md"
    manifest.write_text("\n".join(lines), encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="re-download everything")
    parser.add_argument("--only", nargs="*", help="only these source keys")
    args = parser.parse_args(argv)

    selected = [s for s in SOURCES if not args.only or s.key in args.only]
    if not selected:
        print("No sources matched.", file=sys.stderr)
        return 1

    print(f"Downloading {len(selected)} source(s) into {RAW_DIR}")
    paths: dict[str, Path] = {}
    failures: list[tuple[str, str]] = []
    for source in selected:
        try:
            paths[source.key] = fetch(source, force=args.force)
        except Exception as exc:                      # keep going; report at the end
            print(f"  FAILED   {source.filename}: {exc}")
            failures.append((source.key, str(exc)))

    manifest = write_manifest(paths)
    print(f"\nManifest written to {manifest}")

    if failures:
        print(f"\n{len(failures)} source(s) failed:", file=sys.stderr)
        for key, err in failures:
            print(f"  - {key}: {err}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
